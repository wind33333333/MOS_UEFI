  #include "cpu_registers.h"

  .code64
  .section .text, "ax"

  #================= 系统调用汇编入口 ==========================

    # 引用段选择子定义 (与 GDT 严格匹配)
    .set USER_CS, 0x1B      # 例如 GDT 索引 3，RPL=3 (0x18 | 3)
    .set USER_DS, 0x23      # 例如 GDT 索引 4，RPL=3 (0x20 | 3)

    # Per-CPU 结构体内部偏移 (通过 %gs: 寻址)
    .set PERCPU_KERNEL_STACK_TOP, 0x00    # 当前 CPU 的内核栈顶
    .set PERCPU_USER_RSP,   0x08    # 暂存用户栈指针的临时槽位

    .extern do_syscall_dispatcher
    .global syscall_entry
    .align 16
    syscall_entry:
        # -------------------------------------------------------------
        # 1. 特权级切换与换栈 (绝对关键防御)
        # -------------------------------------------------------------
        # 此时 CPU 处于 Ring 0，但 %rsp 依然是不可信的用户栈！
        swapgs                              # 换入内核 Per-CPU 结构体基地址到 GS_BASE
        movq %rsp, %gs:PERCPU_USER_RSP      # 将用户态 RSP 暂存到 Per-CPU 变量中
        movq %gs:PERCPU_KERNEL_STACK_TOP, %rsp    # 切换至安全的内核栈顶

        # -------------------------------------------------------------
        # 2. 构造 cpu_registers_t 的硬件栈现场 (模拟 IDT 压栈布局)
        # -------------------------------------------------------------
        pushq $USER_DS                      # 压入 SS (用户数据段选择子)
        pushq %gs:PERCPU_USER_RSP           # 压入 RSP (从暂存槽捞出用户栈指针)
        pushq %r11                          # 压入 RFLAGS (硬件已将进入前的 RFLAGS 存入 R11)
        pushq $USER_CS                      # 压入 CS (用户代码段选择子)
        pushq %rcx                          # 压入 RIP (硬件已将进入前的 RIP 存入 RCX)

        # -------------------------------------------------------------
        # 3. 构造元数据 (错误码与中断号)
        # -------------------------------------------------------------
        pushq $0                            # 伪造 err_code = 0
        pushq $0x80                         # 标记 int_no = 0x80 (系统调用特征标识)

        # -------------------------------------------------------------
        # 4. 保存 15 个通用寄存器
        # -------------------------------------------------------------
        SAVE_ALL_REGS

        # -------------------------------------------------------------
        # 5. 传参并调用 C 语言分发器
        # -------------------------------------------------------------
        # System V AMD64 ABI 约定：第 1 个参数通过 %rdi 传递
        # 此时 %rsp 刚好指向 cpu_registers_t 结构体的起始地址 (r15)
        movq %rsp, %rdi
        call do_syscall_dispatcher

        # -------------------------------------------------------------
        # 6. 处理返回值并注入现场
        # -------------------------------------------------------------
        # do_syscall_dispatcher 的返回值在 %rax 中。
        # 覆写栈上保存的 RAX 槽位 (偏移 0x70 = 112 字节)。
        # 这样随后的 RESTORE_ALL_REGS 就会直接把返回值恢复到 %rax 中。
        movq %rax, 0x70(%rsp)

        # -------------------------------------------------------------
        # 7. 恢复现场并返回用户态 (sysretq 极速路径)
        # -------------------------------------------------------------
        RESTORE_ALL_REGS                    # 恢复通用寄存器 (RAX 此时已带上系统调用返回值)

        addq $16, %rsp                      # 跨过 int_no 与 err_code (16 字节)

        # 弹出并准备 sysretq 所需的硬件寄存器
        popq %rcx                           # 恢复用户目标 RIP 到 RCX
        addq $8, %rsp                       # 跨过 CS (sysretq 根据 MSR STAR 自动加载，无需手动恢复)
        popq %r11                           # 恢复用户 RFLAGS 到 R11
        popq %rsp                           # 恢复用户栈指针 RSP (切回用户栈)
        # 此时内核栈已完全弹空

        swapgs                              # 换回用户态 GS
        sysretq                             # 极速还阳：从 RCX 恢复 RIP，从 R11 恢复 RFLAGS，CPL=3
